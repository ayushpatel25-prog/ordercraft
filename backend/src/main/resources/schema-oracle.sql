-- ====================================================================
-- ORDERCRAFT Manufacturing Order Management System (OMS)
-- Oracle Database 19c / 21c / 23c Enterprise Schema
-- ====================================================================

-- 1. SECURITY & ROLES
CREATE TABLE roles (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE permissions (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE,
    module VARCHAR2(50) NOT NULL,
    description VARCHAR2(255)
);

CREATE TABLE role_permissions (
    role_id NUMBER(19) NOT NULL,
    permission_id NUMBER(19) NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_permission FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
);

CREATE TABLE users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE user_roles (
    user_id NUMBER(19) NOT NULL,
    role_id NUMBER(19) NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
);

-- 2. CUSTOMER MANAGEMENT
CREATE TABLE customers (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    phone VARCHAR2(30),
    address VARCHAR2(255),
    city VARCHAR2(100),
    state VARCHAR2(100),
    postal_code VARCHAR2(20),
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_customers_email ON customers(email);

-- 3. PRODUCT & BOM
CREATE TABLE products (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    sku VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(500),
    unit_price NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    unit VARCHAR2(20) DEFAULT 'PCS' NOT NULL,
    category VARCHAR2(50) NOT NULL, -- FINISHED_GOOD, RAW_MATERIAL, SUB_ASSEMBLY
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_products_sku ON products(sku);

CREATE TABLE boms (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER(19) NOT NULL,
    version VARCHAR2(20) DEFAULT '1.0' NOT NULL,
    description VARCHAR2(255),
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bom_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT uq_bom_product_version UNIQUE (product_id, version)
);

CREATE TABLE bom_items (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_id NUMBER(19) NOT NULL,
    material_id NUMBER(19) NOT NULL,
    quantity_required NUMBER(12,4) NOT NULL,
    unit VARCHAR2(20) NOT NULL,
    CONSTRAINT fk_bom_item_bom FOREIGN KEY (bom_id) REFERENCES boms(id) ON DELETE CASCADE,
    CONSTRAINT fk_bom_item_material FOREIGN KEY (material_id) REFERENCES products(id)
);

-- 4. INVENTORY MANAGEMENT
CREATE TABLE inventory (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER(19) NOT NULL UNIQUE,
    quantity NUMBER(14,2) DEFAULT 0.00 NOT NULL,
    reserved_quantity NUMBER(14,2) DEFAULT 0.00 NOT NULL,
    available_quantity NUMBER(14,2) GENERATED ALWAYS AS (quantity - reserved_quantity) VIRTUAL,
    reorder_level NUMBER(14,2) DEFAULT 10.00 NOT NULL,
    location VARCHAR2(100) DEFAULT 'Warehouse A' NOT NULL,
    status VARCHAR2(20) DEFAULT 'IN_STOCK' NOT NULL,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT chk_inv_qty CHECK (quantity >= 0),
    CONSTRAINT chk_inv_reserved CHECK (reserved_quantity >= 0)
);

CREATE TABLE inventory_transactions (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER(19) NOT NULL,
    transaction_type VARCHAR2(30) NOT NULL, -- RECEIVED, RESERVED, RELEASED, CONSUMED, ADJUSTED
    quantity NUMBER(14,2) NOT NULL,
    previous_quantity NUMBER(14,2) NOT NULL,
    new_quantity NUMBER(14,2) NOT NULL,
    reference_type VARCHAR2(50), -- SALES_ORDER, WORK_ORDER, PURCHASE_ORDER, MANUAL
    reference_id VARCHAR2(100),
    notes VARCHAR2(255),
    performed_by VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_inv_tx_product FOREIGN KEY (product_id) REFERENCES products(id)
);

-- 5. SALES ORDERS
CREATE TABLE sales_orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR2(50) NOT NULL UNIQUE,
    customer_id NUMBER(19) NOT NULL,
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expected_delivery_date DATE,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    subtotal NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    tax_amount NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    total_amount NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    created_by VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_so_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);
CREATE INDEX idx_so_number ON sales_orders(order_number);
CREATE INDEX idx_so_status ON sales_orders(status);

CREATE TABLE sales_order_items (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id NUMBER(19) NOT NULL,
    product_id NUMBER(19) NOT NULL,
    quantity NUMBER(12,2) NOT NULL,
    unit_price NUMBER(15,2) NOT NULL,
    total_price NUMBER(15,2) NOT NULL,
    CONSTRAINT fk_so_items_order FOREIGN KEY (sales_order_id) REFERENCES sales_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_so_items_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT chk_so_item_qty CHECK (quantity > 0)
);

-- 6. WORK ORDERS (PRODUCTION)
CREATE TABLE work_orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_number VARCHAR2(50) NOT NULL UNIQUE,
    sales_order_id NUMBER(19),
    product_id NUMBER(19) NOT NULL,
    quantity NUMBER(12,2) NOT NULL,
    start_date DATE,
    expected_end_date DATE,
    actual_end_date DATE,
    status VARCHAR2(30) DEFAULT 'PLANNED' NOT NULL,
    assigned_to VARCHAR2(100),
    progress_percentage NUMBER(5,2) DEFAULT 0.00 NOT NULL,
    notes VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_wo_so FOREIGN KEY (sales_order_id) REFERENCES sales_orders(id) ON DELETE SET NULL,
    CONSTRAINT fk_wo_product FOREIGN KEY (product_id) REFERENCES products(id)
);
CREATE INDEX idx_wo_number ON work_orders(work_order_number);

-- 7. SUPPLIERS & PROCUREMENT
CREATE TABLE suppliers (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    contact_person VARCHAR2(100),
    email VARCHAR2(100),
    phone VARCHAR2(30),
    address VARCHAR2(255),
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE purchase_orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_number VARCHAR2(50) NOT NULL UNIQUE,
    supplier_id NUMBER(19) NOT NULL,
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expected_delivery_date DATE,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    total_amount NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    created_by VARCHAR2(100),
    approved_by VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);
CREATE INDEX idx_po_number ON purchase_orders(purchase_order_number);

CREATE TABLE purchase_order_items (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id NUMBER(19) NOT NULL,
    material_id NUMBER(19) NOT NULL,
    quantity NUMBER(12,2) NOT NULL,
    received_quantity NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    unit_price NUMBER(15,2) NOT NULL,
    total_price NUMBER(15,2) NOT NULL,
    CONSTRAINT fk_poi_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_poi_material FOREIGN KEY (material_id) REFERENCES products(id),
    CONSTRAINT chk_poi_qty CHECK (quantity > 0)
);

-- 8. INVOICES & PAYMENTS
CREATE TABLE invoices (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR2(50) NOT NULL UNIQUE,
    sales_order_id NUMBER(19) NOT NULL,
    customer_id NUMBER(19) NOT NULL,
    invoice_date DATE DEFAULT SYSDATE NOT NULL,
    due_date DATE NOT NULL,
    subtotal NUMBER(15,2) NOT NULL,
    tax NUMBER(15,2) NOT NULL,
    total_amount NUMBER(15,2) NOT NULL,
    paid_amount NUMBER(15,2) DEFAULT 0.00 NOT NULL,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_invc_so FOREIGN KEY (sales_order_id) REFERENCES sales_orders(id),
    CONSTRAINT fk_invc_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);
CREATE INDEX idx_invc_number ON invoices(invoice_number);

CREATE TABLE payments (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_reference VARCHAR2(50) NOT NULL UNIQUE,
    invoice_id NUMBER(19) NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    amount NUMBER(15,2) NOT NULL,
    payment_method VARCHAR2(30) NOT NULL, -- CASH, BANK_TRANSFER, CARD, UPI, CHEQUE
    transaction_reference VARCHAR2(100),
    status VARCHAR2(30) DEFAULT 'COMPLETED' NOT NULL,
    notes VARCHAR2(255),
    recorded_by VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_pmt_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id),
    CONSTRAINT chk_pmt_amt CHECK (amount > 0)
);

-- 9. NOTIFICATIONS & AUDIT LOGS
CREATE TABLE notifications (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(150) NOT NULL,
    message VARCHAR2(500) NOT NULL,
    type VARCHAR2(30) DEFAULT 'INFO' NOT NULL, -- INFO, WARNING, SUCCESS, ALERT
    target_role VARCHAR2(50),
    is_read NUMBER(1) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE audit_logs (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100) NOT NULL,
    action VARCHAR2(100) NOT NULL,
    entity_type VARCHAR2(50) NOT NULL,
    entity_id VARCHAR2(100) NOT NULL,
    old_value CLOB,
    new_value CLOB,
    ip_address VARCHAR2(45),
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_audit_timestamp ON audit_logs(timestamp DESC);
